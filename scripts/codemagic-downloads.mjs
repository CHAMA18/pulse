#!/usr/bin/env node

/**
 * Refreshes src/lib/desktop-downloads.ts from the latest successful
 * Codemagic builds.
 *
 * The Codemagic artifact URLs themselves require the API token, so this
 * script converts the newest macOS and Windows installers into long-lived
 * public download URLs. That keeps the token out of the browser while the
 * static site (GitHub Pages) can still download the real builds.
 *
 * Usage:
 *   CODEMAGIC_API_TOKEN=... npm run desktop:downloads
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://api.codemagic.io";
const APP_ID = process.env.CODEMAGIC_APP_ID?.trim() || "6af775a24cd793dd9f8cb82b";
const TOKEN = process.env.CODEMAGIC_API_TOKEN?.trim();
const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/lib/desktop-downloads.ts"
);
const EXPIRES_AT = Math.floor(Date.now() / 1000) + 10 * 365 * 24 * 60 * 60;

if (!TOKEN) {
  console.error(
    "CODEMAGIC_API_TOKEN is required. Find it in Codemagic → Account settings → API token."
  );
  process.exit(1);
}

async function api(path, init = {}) {
  const response = await fetch(`${API}${path}`, {
    ...init,
    headers: {
      "Content-Type": "application/json",
      "x-auth-token": TOKEN,
      ...(init.headers ?? {}),
    },
  });
  const body = await response.json().catch(() => null);
  if (!response.ok) {
    throw new Error(
      `${path} failed (${response.status}): ${body?.message ?? response.statusText}`
    );
  }
  return body;
}

async function latestArtifact(buildName, matches) {
  const list = await api(`/builds?appId=${APP_ID}&limit=50`);
  const builds = (list.builds ?? [])
    .filter((build) => build.status === "finished" && build.config?.name === buildName)
    .sort((a, b) => Date.parse(b.createdAt) - Date.parse(a.createdAt));

  for (const build of builds) {
    const detail = await api(`/builds/${build._id}`);
    const artefacts = detail.build?.artefacts ?? [];
    const artifact = artefacts.find((entry) => matches.some((match) => match.test(entry.name)));
    if (artifact) return { build, artifact };
  }

  throw new Error(`No downloadable artifact found for "${buildName}".`);
}

async function publicUrl(artifact) {
  const path = artifact.path
    .split("/")
    .map((segment) => encodeURIComponent(segment))
    .join("/");
  const result = await api(`/artifacts/${path}/public-url`, {
    method: "POST",
    body: JSON.stringify({ expiresAt: EXPIRES_AT }),
  });
  if (!result?.url) throw new Error(`No public URL returned for ${artifact.name}.`);
  return result.url;
}

const mac = await latestArtifact("Pulse for macOS", [
  /-mac-arm64\.zip$/i,
  /-mac-x64\.zip$/i,
]);
const windows = await latestArtifact("Pulse for Windows", [/-win-x64\.zip$/i]);

const [macUrl, windowsUrl] = await Promise.all([
  publicUrl(mac.artifact),
  publicUrl(windows.artifact),
]);

const generated = `/**
 * Direct desktop downloads from the latest successful Codemagic builds.
 *
 * Generated by \`npm run desktop:downloads\` on ${new Date().toISOString()}.
 * The links are public Codemagic artifact URLs (expire ${new Date(EXPIRES_AT * 1000).toISOString()});
 * regenerate them after shipping a new desktop build.
 */
export const DESKTOP_DOWNLOADS = {
  macos: ${JSON.stringify(macUrl)},
  windows: ${JSON.stringify(windowsUrl)},
} as const;
`;

writeFileSync(OUTPUT, generated);
console.log(`Wrote ${OUTPUT}`);
console.log(`macOS   ${mac.build._id} · ${mac.artifact.name}`);
console.log(`Windows ${windows.build._id} · ${windows.artifact.name}`);
